"""Export the Pydantic API contract to JSON Schema (ADR-0007).

Usage:
    python scripts/export_contract.py          # write src/faststudio/schemas/contract.schema.json
    python scripts/export_contract.py --check  # exit 1 if the committed file is stale

The output is deterministic (sorted keys, stable ``$defs`` names) so CI can
fail on drift with ``--check``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, get_args

from pydantic import BaseModel
from pydantic.json_schema import JsonSchemaMode, models_json_schema

from faststudio.schemas import contract

OUTPUT = (
    Path(__file__).resolve().parents[1]
    / "src"
    / "faststudio"
    / "schemas"
    / ("contract.schema.json")
)

# Top-level API shapes; nested models are reached through them.
RESPONSES: tuple[type[BaseModel], ...] = (
    contract.MetaResponse,
    contract.UserResponse,
    contract.ListResponse,
    contract.Row,
    contract.ChoicesResponse,
    contract.ErrorResponse,
)
REQUESTS: tuple[type[BaseModel], ...] = (contract.LoginRequest,)
# Literal unions emitted as named definitions so generated code can share them.
NAMED_ENUMS: dict[str, list[str]] = {
    "FieldType": list(get_args(contract.FieldType)),
    "ErrorCode": list(get_args(contract.ErrorCode)),
}


_LITERAL_KEYS = frozenset({"default", "const", "examples", "enum"})


def _inline_named_enums(node: object) -> list[str]:
    """Return named enums still inlined anywhere in ``node`` (should be none)."""
    if isinstance(node, list):
        return [name for item in node for name in _inline_named_enums(item)]
    if not isinstance(node, dict):
        return []
    found = [name for name, values in NAMED_ENUMS.items() if node.get("enum") == values]
    return found + [name for value in node.values() for name in _inline_named_enums(value)]


def _tidy(node: object) -> object:
    """Drop per-property titles and replace known enums with ``$ref``s."""
    if isinstance(node, list):
        return [_tidy(item) for item in node]
    if not isinstance(node, dict):
        return node
    for name, values in NAMED_ENUMS.items():
        if node.get("enum") == values:
            ref: dict[str, Any] = {"$ref": f"#/$defs/{name}"}
            if "description" in node:
                ref["description"] = node["description"]
            return ref
    tidied: dict[str, object] = {}
    for key, value in node.items():
        if key == "title":
            continue  # a schema annotation, not data
        if key in _LITERAL_KEYS:
            tidied[key] = value  # data, not a schema: never rewrite
            continue
        if key == "properties" and isinstance(value, dict):
            # Keys here are field names (a model may have a field called "title").
            tidied[key] = {name: _tidy(sub) for name, sub in value.items()}
        else:
            tidied[key] = _tidy(value)
    return tidied


def build_schema() -> dict[str, Any]:
    """Return the combined JSON Schema document for the contract."""
    pairs: list[tuple[type[BaseModel], JsonSchemaMode]] = [
        *((model, "serialization") for model in RESPONSES),
        *((model, "validation") for model in REQUESTS),
    ]
    _, schema = models_json_schema(pairs, ref_template="#/$defs/{model}")
    definitions: dict[str, Any] = {name: _tidy(body) for name, body in schema["$defs"].items()}
    leftover = _inline_named_enums(definitions)
    if leftover:  # pragma: no cover - guards against pydantic changing Literal output
        msg = f"named enums left inline: {sorted(set(leftover))}"
        raise RuntimeError(msg)
    for name, values in NAMED_ENUMS.items():
        definitions[name] = {"type": "string", "enum": values}
    names = sorted(model.__name__ for model, _ in pairs)
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "FastStudioContract",
        "description": (
            f"FastStudio API contract, schema_version {contract.SCHEMA_VERSION}. "
            "Generated by scripts/export_contract.py - do not edit."
        ),
        "type": "object",
        # One property per top-level shape so code generators emit every type.
        "properties": {name: {"$ref": f"#/$defs/{name}"} for name in names},
        "additionalProperties": False,
        "$defs": definitions,
    }


def render(schema: dict[str, Any]) -> str:
    """Serialize deterministically."""
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def main(argv: list[str]) -> int:
    """CLI entry point."""
    if argv not in ([], ["--check"]):
        print(__doc__, file=sys.stderr)
        return 2
    text = render(build_schema())
    if argv == ["--check"]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(
                f"ERROR: {OUTPUT} is out of date; run `python scripts/export_contract.py`.",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {OUTPUT.name} is up to date")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
